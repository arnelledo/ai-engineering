#
# AI Engineering Framework - Claude Code adapter.
#
# Translates the canonical framework into Claude Code's native format.
# Dot-sourced by scripts/install.ps1; registers itself in $HarnessAdapters.
#
# Generated (framework-owned):
#
#   .claude/rules/ai-engineering.md       always-loaded project rules
#   .claude/agents/<agent>.md             subagents
#   .claude/skills/<command>/SKILL.md     slash commands
#
# Never created or modified:
#
#   CLAUDE.md, .claude/settings.json      owned by the repository team
#
# Design notes:
#
#   - Repository-wide standards go to .claude/rules/, not CLAUDE.md. Rules
#     load in every session and in every subagent, so agents receive only
#     their role-specific standards. Creating a CLAUDE.md would also stop
#     Claude Code from reading an existing AGENTS.md.
#   - Specialist commands run in their agent (context: fork), so the
#     agent's tool restrictions apply, as with Copilot prompts.
#   - Orchestrator commands run in the main conversation, because a forked
#     subagent cannot ask the user questions and the Orchestrator's human
#     checkpoints depend on that.
#   - All commands are explicit slash commands (disable-model-invocation).
#

$ClaudeToolMap = @{
    read    = @("Read")
    search  = @("Grep", "Glob")
    edit    = @("Edit", "Write", "NotebookEdit")
    execute = @("Bash", "PowerShell")
    web     = @("WebFetch", "WebSearch")
    todo    = @("TodoWrite")
    ask     = @("AskUserQuestion")
    # agent is expanded per agent: Agent(<allowed subagents>)
}

function ConvertTo-ClaudeTools {
    param([hashtable]$Agent)

    $tools = @()

    foreach ($capability in $Agent.Tools) {

        if ($capability -eq "agent") {
            # Allowlist of subagents the agent may spawn.
            $tools += "Agent($($Agent.Agents -join ', '))"
            continue
        }

        $tools += $ClaudeToolMap[$capability]
    }

    return $tools
}

# ===========================================================================
# Rules (repository-wide instructions)
# ===========================================================================

function New-ClaudeRules {

    $sections = foreach ($standard in $Framework.InstructionStandards) {
        Get-EmbeddedStandard $standard
    }

    $header = @"
# AI Engineering Instructions

These instructions define the baseline engineering expectations for this
repository. This file is generated by the AI Engineering Framework installer
and is replaced on framework updates. Do not edit it directly.

Repository-specific instructions belong in ``CLAUDE.md``. Project-specific
knowledge belongs under ``.ai/``.

Project-specific architecture, business rules, persistence requirements,
and explicit task instructions take precedence over generic framework
guidance when they are more specific.

The framework's agents are defined in ``.claude/agents/``. For non-trivial
work, run the session as the Orchestrator (``claude --agent orchestrator``)
or use a workflow command such as ``/feature`` or ``/bug-fix``.
"@

    return (@($header.Trim()) + $sections) -join "`n`n"
}

# ===========================================================================
# Agents
# ===========================================================================

function New-ClaudeAgentContent {

    param([hashtable]$Agent)

    if ($Agent.Name -match "[:\s]") {
        throw "Claude Code agent names cannot contain ':' or whitespace: '$($Agent.Name)'."
    }

    # Shared standards are omitted: they are in .claude/rules/, which Claude
    # Code loads into every subagent.

    $parts = @((Read-TextFile (Join-Path $AgentsRoot "$($Agent.Name).md")).Trim())

    foreach ($standard in (Get-AgentStandards $Agent.Name)) {
        $parts += Get-EmbeddedStandard $standard
    }

    $body = $parts -join "`n`n"

    $frontmatter = @(
        "---",
        "name: $($Agent.Name)",
        "description: $(ConvertTo-YamlDoubleQuoted $Agent.Description)",
        "tools: $((ConvertTo-ClaudeTools $Agent) -join ', ')",
        "---"
    )

    return ($frontmatter -join "`n") + "`n`n" + $body
}

# ===========================================================================
# Skills (slash commands)
# ===========================================================================

$ClaudeWorkingTreeChangesBlock = @'
## Current Changes

Working tree status:

!`git status --short`

Unstaged changes:

!`git diff --no-color`

Staged changes:

!`git diff --cached --no-color`
'@

function New-ClaudeSkillContent {

    param([hashtable]$Command)

    $runsInMainConversation = $Command.Agent -eq "orchestrator"

    $frontmatter = @(
        "---",
        "name: $($Command.Name)",
        "description: $(ConvertTo-YamlDoubleQuoted $Command.Description)"
    )

    if ($Command.ContainsKey("ArgumentHint")) {
        $frontmatter += "argument-hint: $(ConvertTo-YamlDoubleQuoted $Command.ArgumentHint)"
    }

    $frontmatter += "disable-model-invocation: true"

    if (-not $runsInMainConversation) {
        $frontmatter += "context: fork"
        $frontmatter += "agent: $($Command.Agent)"
    }

    $includeChanges = $Command.ContainsKey("IncludeWorkingTreeChanges") -and $Command.IncludeWorkingTreeChanges

    if ($includeChanges) {
        # Pre-approves only the read-only git commands injected below, so
        # the read-only agent receives the diff without shell access.
        $frontmatter += "allowed-tools: Bash(git status *), Bash(git diff *)"
    }

    $frontmatter += "---"

    $parts = @()

    if ($runsInMainConversation) {
        $parts += "Run this command as the Orchestrator. If this session was not started with ``claude --agent orchestrator``, read ``.claude/agents/orchestrator.md`` now and follow it for the rest of this task, delegating each phase to the specialist subagents it names."
    }

    $parts += (Get-CommandBody $Command).Trim()

    if ($includeChanges) {
        $parts += $ClaudeWorkingTreeChangesBlock.Trim()
    }

    $parts += "## Request`n`n`$ARGUMENTS"

    return ($frontmatter -join "`n") + "`n`n" + ($parts -join "`n`n")
}

# ===========================================================================
# Adapter entry point
# ===========================================================================

function Install-ClaudeHarness {

    $claudeRoot = Join-Path $TargetRepo ".claude"

    Write-Step "Generating Claude Code rules"

    Write-GeneratedFile `
        -Path (Join-Path $claudeRoot "rules/ai-engineering.md") `
        -Content (New-ClaudeRules) | Out-Null

    Write-Step "Generating Claude Code subagents"

    foreach ($agent in $Framework.Agents) {
        Write-GeneratedFile `
            -Path (Join-Path $claudeRoot "agents/$($agent.Name).md") `
            -Content (New-ClaudeAgentContent $agent) | Out-Null
    }

    Write-Step "Generating Claude Code skills"

    foreach ($command in $Framework.Commands) {
        Write-GeneratedFile `
            -Path (Join-Path $claudeRoot "skills/$($command.Name)/SKILL.md") `
            -Content (New-ClaudeSkillContent $command) | Out-Null
    }

    $hasClaudeMd = (Test-Path -LiteralPath (Join-Path $TargetRepo "CLAUDE.md")) -or
        (Test-Path -LiteralPath (Join-Path $claudeRoot "CLAUDE.md"))

    if (-not $hasClaudeMd) {
        Write-Info "No CLAUDE.md found. The installer does not create one. Add repository-specific instructions to CLAUDE.md when needed (note: a CLAUDE.md stops Claude Code from reading AGENTS.md by default)."
    }
}

$HarnessAdapters["Claude"] = @{
    Id              = "claude-code"
    DisplayName     = "Claude Code"
    InstallFunction = "Install-ClaudeHarness"

    # Paths the stale-file cleanup may remove generated files from.
    ManagedPrefixes = @(
        ".claude/agents/",
        ".claude/skills/",
        ".claude/rules/ai-engineering.md"
    )

    ProjectOwned    = @()

    NextSteps       = @(
        "Start Claude Code in the repository as the Orchestrator: claude --agent orchestrator",
        "Run /bootstrap-knowledge to discover and populate persistent project knowledge",
        "Review the generated .ai/ knowledge",
        "Use /code-review or the reviewer subagent to independently validate the initial knowledge when appropriate",
        "Correct any unsupported or inaccurate claims",
        "Add repository-specific rules to CLAUDE.md (never modified by the installer)",
        "Commit .claude/agents/, .claude/skills/, .claude/rules/ and reviewed .ai/ knowledge with the application repository",
        "Continue normal development using the Orchestrator"
    )
}
