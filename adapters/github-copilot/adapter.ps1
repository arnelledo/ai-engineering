#
# AI Engineering Framework - GitHub Copilot adapter.
#
# Translates the canonical framework into GitHub Copilot's native format.
# Dot-sourced by scripts/install.ps1; registers itself in $HarnessAdapters.
#
# Generated (framework-owned):
#
#   .github/copilot-instructions.md
#   .github/agents/<agent>.agent.md
#   .github/prompts/<command>.prompt.md
#
# Project-owned (created once, never overwritten):
#
#   .github/instructions/project.instructions.md
#
# Tool capabilities map to the cross-platform tool-set aliases understood by
# both VS Code and the Copilot coding agent on GitHub.com. Unrecognized tool
# names are ignored by both.
#

$CopilotToolMap = @{
    read    = @("read")
    search  = @("search")
    edit    = @("edit")
    execute = @("execute")
    agent   = @("agent")
    web     = @("web")
    todo    = @("todo")
    ask     = @()
}

function ConvertTo-CopilotTools {
    param([string[]]$Capabilities)

    $tools = @()

    foreach ($capability in $Capabilities) {
        $tools += $CopilotToolMap[$capability]
    }

    return $tools
}

# ===========================================================================
# Repository-wide instructions
# ===========================================================================

function New-CopilotInstructions {

    $sections = foreach ($standard in $Framework.InstructionStandards) {
        Get-EmbeddedStandard $standard
    }

    $header = @"
# AI Engineering Instructions

These instructions define the baseline engineering expectations for this
repository. This file is generated by the AI Engineering Framework installer
and is replaced on framework updates. Do not edit it directly.

Repository-specific instructions belong in
``.github/instructions/project.instructions.md``. Project-specific knowledge
belongs under ``.ai/``.

Project-specific architecture, business rules, persistence requirements,
and explicit task instructions take precedence over generic framework
guidance when they are more specific.
"@

    return (@($header.Trim()) + $sections) -join "`n`n"
}

# ===========================================================================
# Agents
# ===========================================================================

function New-CopilotAgentContent {

    param([hashtable]$Agent)

    # Copilot subagents start with their own context and may not receive
    # the repository-wide instructions, so each agent is self-contained:
    # it receives its role-specific standards and the shared standards.

    $parts = @((Read-TextFile (Join-Path $AgentsRoot "$($Agent.Name).md")).Trim())

    foreach ($standard in (Get-AgentStandards $Agent.Name -IncludeShared)) {
        $parts += Get-EmbeddedStandard $standard
    }

    $body = $parts -join "`n`n"

    $frontmatter = @(
        "---",
        "description: $(ConvertTo-YamlDoubleQuoted $Agent.Description)"
    )

    if ($Agent.ContainsKey("ArgumentHint")) {
        $frontmatter += "argument-hint: $(ConvertTo-YamlDoubleQuoted $Agent.ArgumentHint)"
    }

    $frontmatter += "tools: $(ConvertTo-YamlInlineList (ConvertTo-CopilotTools $Agent.Tools))"

    if ($Agent.ContainsKey("Agents")) {
        # Agent names are the file names, which Copilot uses as the
        # default agent name.
        $frontmatter += "agents: $(ConvertTo-YamlInlineList $Agent.Agents)"
    }

    $frontmatter += "---"

    return ($frontmatter -join "`n") + "`n`n" + $body
}

# ===========================================================================
# Prompts
# ===========================================================================

function Get-CopilotPromptName {
    param([hashtable]$Command)

    if ($Command.ContainsKey("CopilotName")) {
        return $Command.CopilotName
    }

    return $Command.Name
}

function New-CopilotPromptContent {

    param([hashtable]$Command)

    $body = Get-CommandBody $Command

    $frontmatter = @(
        "---",
        "description: $(ConvertTo-YamlDoubleQuoted $Command.Description)"
    )

    if ($Command.ContainsKey("ArgumentHint")) {
        $frontmatter += "argument-hint: $(ConvertTo-YamlDoubleQuoted $Command.ArgumentHint)"
    }

    $frontmatter += "agent: $(ConvertTo-YamlDoubleQuoted $Command.Agent)"
    $frontmatter += "---"

    return ($frontmatter -join "`n") + "`n`n" + $body
}

# ===========================================================================
# Project-owned instructions
# ===========================================================================

function Install-CopilotProjectInstructions {

    # Repository-specific, always-applied Copilot rules. Owned by the
    # application repository: created once, never overwritten, even with
    # -Force. This is where teams customize Copilot behavior without
    # editing the framework-generated copilot-instructions.md.

    Write-Step "Creating project-owned Copilot instructions"

    $content = @'
---
applyTo: "**"
---

# Project Instructions

<!--
Repository-specific instructions for GitHub Copilot.

This file is owned by this repository. The AI Engineering Framework installer
creates it once and never overwrites it, so customizations here survive
framework updates. Do not edit .github/copilot-instructions.md instead; that
file is replaced on every framework update.

Keep this file short. It is applied to every Copilot request in this
repository. Add rules such as:

- authoritative build and test commands;
- repository-specific coding conventions;
- directories or files that must not be modified.

Durable project knowledge (business rules, architecture, persistence and
integration behavior) belongs under .ai/, not here.
-->
'@

    Write-ScaffoldFile `
        -Path (Join-Path $TargetRepo ".github/instructions/project.instructions.md") `
        -Content $content
}

# ===========================================================================
# Adapter entry point
# ===========================================================================

function Install-GitHubCopilotHarness {

    $gitHubRoot = Join-Path $TargetRepo ".github"

    Write-Step "Generating repository Copilot instructions"

    Write-GeneratedFile `
        -Path (Join-Path $gitHubRoot "copilot-instructions.md") `
        -Content (New-CopilotInstructions) | Out-Null

    Write-Step "Generating Copilot custom agents"

    foreach ($agent in $Framework.Agents) {
        Write-GeneratedFile `
            -Path (Join-Path $gitHubRoot "agents/$($agent.Name).agent.md") `
            -Content (New-CopilotAgentContent $agent) | Out-Null
    }

    Write-Step "Generating Copilot prompts"

    foreach ($command in $Framework.Commands) {
        Write-GeneratedFile `
            -Path (Join-Path $gitHubRoot "prompts/$(Get-CopilotPromptName $command).prompt.md") `
            -Content (New-CopilotPromptContent $command) | Out-Null
    }

    Install-CopilotProjectInstructions
}

$HarnessAdapters["GitHubCopilot"] = @{
    Id              = "github-copilot"
    DisplayName     = "GitHub Copilot"
    InstallFunction = "Install-GitHubCopilotHarness"

    # Paths the stale-file cleanup may remove generated files from.
    ManagedPrefixes = @(".github/")

    ProjectOwned    = @(".github/instructions/project.instructions.md")

    NextSteps       = @(
        "Open the repository in VS Code",
        "Select the Orchestrator agent in Copilot Chat",
        "Run /bootstrap-knowledge to discover and populate persistent project knowledge",
        "Review the generated .ai/ knowledge",
        "Use the Reviewer agent to independently validate the initial knowledge when appropriate",
        "Correct any unsupported or inaccurate claims",
        "Add repository-specific Copilot rules to .github/instructions/project.instructions.md",
        "Commit .github/ and reviewed .ai/ knowledge with the application repository",
        "Continue normal development using the Orchestrator"
    )
}
